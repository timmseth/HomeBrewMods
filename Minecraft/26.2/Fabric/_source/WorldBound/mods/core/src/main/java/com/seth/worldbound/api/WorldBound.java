package com.seth.worldbound.api;

import com.seth.worldbound.Earth;
import com.seth.worldbound.worldgen.EarthBiomeSource;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.server.level.ServerLevel;

/**
 * The public face of the WorldBound engine, for add-ons (Fossil Record, Landmarks, TATV) and other mods.
 * Everything here is safe to call from the server thread; the lat/lon and data lookups also from worldgen threads.
 *
 * <pre>
 *   if (WorldBound.isEarthWorld(level)) {
 *       double[] ll = WorldBound.latLon(pos);           // {lat, lon}
 *       int koppen = WorldBound.climate(pos);           // Beck et al. Köppen class 1-30
 *   }
 * </pre>
 */
public final class WorldBound {
    private WorldBound() {}

    private static volatile Places places;
    private static volatile PlaceNamer namer;

    /** Supplies {@link #places()} (Earth Data World Gen registers its gazetteer). */
    public static void setPlaces(Places p) { places = p; }

    /** Real places, or null when the real Earth isn't installed. */
    public static Places places() { return places; }

    /** Describes a spot in words ("near Boise, Idaho, US (3 km NE)"), for the compass HUD and messages. */
    public interface PlaceNamer {
        String near(double lat, double lon);
    }

    /** The namer for the current world: generated worlds may set their own (Earthish Landmarks names its features). */
    public static void setPlaceNamer(PlaceNamer n) { namer = n; }

    public static boolean hasNamer() { return namer != null; }

    /** Words for where a spot is: the world's own namer, else the real gazetteer on Earth, else coordinates. */
    public static String near(double lat, double lon) {
        PlaceNamer n = namer;
        if (n != null) {
            String s = n.near(lat, lon);
            if (s != null) return s;
        }
        Places p = places;
        if (p != null && !earth().generated()) return p.near(lat, lon);
        return GeoText.latLon(lat, lon);
    }

    private static volatile java.util.function.Supplier<java.util.List<Places.Place>> generatedLandmarks;

    /** Landmarks of a generated world (Earthish Landmarks names the planet's features). */
    public static void setGeneratedLandmarks(java.util.function.Supplier<java.util.List<Places.Place>> s) { generatedLandmarks = s; }

    /**
     * The landmarks of the running world: real ones on Earth (Earth Data World Gen), the planet's own on an
     * Earthish world (Earthish Landmarks); empty when nothing supplies them.
     */
    public static java.util.List<Places.Place> landmarks() {
        if (Earth.get().generated()) {
            var g = generatedLandmarks;
            return g == null ? java.util.List.of() : g.get();
        }
        Places p = places;
        return p == null ? java.util.List.of() : p.landmarks();
    }

    /** True on the server while an Earth or Earthish world is running (and on a client connected to one). */
    public static boolean earthRunning() { return Earth.earthWorld(); }

    /** True if this level is generated by WorldBound (Earth or Earthish). */
    public static boolean isEarthWorld(LevelAccessor level) {
        return level instanceof ServerLevel sl && sl.getChunkSource().getGenerator().getBiomeSource() instanceof EarthBiomeSource
                || level instanceof Level l && l.isClientSide() && Earth.earthWorld();
    }

    /** True if the running world is a generated (Earthish) planet. */
    public static boolean isEarthish() { return Earth.earthWorld() && earth().generated(); }

    /** The engine context of the running world (transform, curve, data). */
    public static Earth earth() { return Earth.get(); }

    /** {latitude, longitude} of a block position. */
    public static double[] latLon(BlockPos pos) {
        var t = Earth.get().activeTransform();
        return new double[]{t.lat(pos.getZ() + 0.5), t.lon(pos.getX() + 0.5)};
    }

    /** Block x and z of a latitude/longitude. */
    public static int[] blockXZ(double lat, double lon) {
        var t = Earth.get().activeTransform();
        return new int[]{(int) Math.floor(t.blockX(lon)), (int) Math.floor(t.blockZ(lat))};
    }

    /** Metres per block, horizontally. */
    public static double scale() { return Earth.get().config.scale_m_per_block; }

    /** Everything known about one column: elevation (m), Köppen class, land cover (ESA WorldCover class), slope... */
    public static Earth.Surface surface(int blockX, int blockZ) { return Earth.get().at(blockX, blockZ); }

    public static double elevationM(BlockPos pos) { return surface(pos.getX(), pos.getZ()).elevM(); }

    /** Köppen-Geiger class, Beck et al. numbering (1 Af ... 29 ET, 30 EF), 0 = none. */
    public static int climate(BlockPos pos) { return surface(pos.getX(), pos.getZ()).climate(); }

    /** ESA WorldCover land-cover class (10 trees, 20 shrubs, 30 grass, 40 crops, 50 built, 60 bare, 70 snow/ice, 80 water...). */
    public static int landCover(BlockPos pos) { return surface(pos.getX(), pos.getZ()).cover(); }

    /** The block height above which snow lies all year at this column (from its climate and latitude). */
    public static int snowlineY(BlockPos pos) {
        Earth e = Earth.get();
        var s = e.at(pos.getX(), pos.getZ());
        return (int) Math.round(e.curve.y(com.seth.worldbound.worldgen.BiomeTable.snowline(s.climate(), s.lat(), s.lon())));
    }
}
